'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const view = read('views/pages/mail.php');
const controller = read('index.php');
const mailer = read('src/Services/MailerService.php');
const transport = read('src/Services/SmtpTransport.php');
const version = read('src/Core/Version.php');

assert(view.includes('name="reply_to"') && view.includes('<textarea'), 'Reply-To must accept multiple addresses');
assert(view.includes('comma') || view.includes('coma') || view.includes('punto y coma'), 'Reply-To separators are documented');
assert(view.includes('name="department_recipients_reply_to"'), 'department Reply-To checkbox is missing');
assert(view.includes("!array_key_exists('department_recipients_reply_to', $smtp) || !empty($smtp['department_recipients_reply_to'])"), 'department Reply-To must default to enabled');
assert(controller.includes("preg_split('/[,;\\\\s]+/'"), 'controller must parse comma, semicolon and newlines');
assert(controller.includes("'reply_to' => $replyTo"), 'multiple Reply-To addresses must be saved');
assert(controller.includes("'department_recipients_reply_to' => isset($_POST['department_recipients_reply_to'])"), 'checkbox must be persisted');
assert(mailer.includes('self::buildDepartmentReplyTo('), 'department Reply-To must use the responsible-aware builder');
assert(mailer.includes('public static function buildDepartmentReplyTo('), 'responsible-aware Reply-To builder is missing');
assert(mailer.includes('strtolower($email) !== $responsibleKey'), 'department responsible must be excluded from Reply-To');
assert(mailer.includes("!array_key_exists('department_recipients_reply_to', $smtp)"), 'department Reply-To must default to enabled for existing settings');
assert(transport.includes(`$headers[] = 'Reply-To: ' . implode(",`), 'Reply-To header must fold safely');
assert(transport.includes("preg_replace('/\\r\\n|\\r|\\n/'"), 'SMTP line endings must be normalized in one regex pass');
assert(transport.includes('rtrim($message, \"\\r\\n\")'), 'SMTP DATA must preserve a valid final CRLF before terminator');
assert(version.includes("VERSION = '1.2.19'"), 'version must be 1.2.4');
assert(view.includes('enctype="multipart/form-data"') && view.includes('name="signature_image"'), 'signature image upload control is missing');
assert(mailer.includes('signatureHtml') && mailer.includes('signatureImage'), 'mailer must inject configured inline signature');
assert(transport.includes('multipart/related') && transport.includes('Content-ID: <'), 'SMTP transport must support CID inline images');
console.log('OK: Reply-To múltiple, firma CID inline, adjunto y encabezado SMTP válido.');
