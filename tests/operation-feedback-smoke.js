'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const app = read('assets/app.js');
const css = read('assets/app.css');
const layout = read('views/layout.php');
const upload = read('views/pages/upload.php');
const history = read('views/pages/history.php');
const updates = read('views/pages/updates.php');
const mail = read('views/pages/mail.php');
const departments = read('views/pages/departments.php');
const users = read('views/pages/users.php');
const version = read('src/Core/Version.php');

assert(!app.includes('window.confirm('), 'native browser confirmations must be replaced by the shared modal');
assert(app.includes("document.querySelector('#confirm-modal')") && app.includes('form.requestSubmit'), 'the shared confirmation modal must submit only after explicit acceptance');
assert(app.includes('approvedSubmissions') && app.includes('data-confirm-variant'), 'confirmation approval and destructive styling must be stateful');
assert(app.includes("document.querySelector('#operation-overlay')") && app.includes('showOperationOverlay'), 'the global operation overlay must exist');
assert(app.includes("window.addEventListener('pageshow'"), 'operation overlay must reset after navigation or BFCache restore');
assert(layout.includes('id="confirm-modal"') && layout.includes('id="operation-overlay"'), 'the app layout must render both shared UI layers');
assert(css.includes('.confirm-modal-backdrop') && css.includes('backdrop-filter:blur(5px)'), 'confirmation dialog must blur the page behind it');
assert(css.includes('.operation-overlay') && css.includes('.operation-spinner') && css.includes('@keyframes operation-spin'), 'long operations must show a visible animated processing state');
assert(upload.includes('data-operation-title="Procesando reporte de asistencia"'), 'XLSX processing must show operation feedback');
assert(history.includes('data-operation-title="Regenerando reporte"') && history.includes('data-operation-title="Enviando reporte por correo"'), 'regeneration and single email actions must show operation feedback');
assert(updates.includes('data-operation-title="Aplicando actualizaciones"') && updates.includes('data-confirm-variant="danger"') && updates.includes('data-operation-title="Restaurando respaldo"'), 'updates and restore must use modal confirmation and processing feedback');
assert(mail.includes('data-operation-title="Probando conexión SMTP"'), 'SMTP test must show operation feedback');
assert(departments.includes('data-confirm-title="Eliminar departamento"') && users.includes('data-confirm-title="Desbloquear cuenta"'), 'department and user confirmations must use the shared modal with contextual labels');
assert(app.includes("event.key === 'Tab'") && app.includes("last.focus()"), "keyboard focus must remain inside the confirmation modal");
assert(version.includes("VERSION = '1.2.31'"), 'release version must be bumped to 1.2.31');
console.log('Operation feedback and confirmation modal smoke: OK');
