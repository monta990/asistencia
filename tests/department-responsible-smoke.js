'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const view = read('views/pages/departments.php');
const controller = read('index.php');
const repository = read('src/Repositories/DepartmentRepository.php');
const mailer = read('src/Services/MailerService.php');
const migration = read('database/migrations/002_department_responsible.php');
const version = read('src/Core/Version.php');

assert(view.indexOf('name="responsible_email"') < view.indexOf('name="recipients"'), 'responsible field must precede department recipients');
assert(view.includes('type="email"') && view.includes('responsable@empresa.com'), 'responsible field must validate as email');
assert(view.includes("$department['responsible_email']"), 'catalog must display responsible address');
assert(controller.includes("(string) ($_POST['responsible_email'] ?? '')"), 'controller must receive responsible address');
assert(repository.includes('responsible_email = :responsible'), 'repository must persist responsible address on update');
assert(repository.includes('public function responsibleEmail(int $departmentId): string'), 'repository must expose responsible address for mail delivery');
assert(repository.includes('public function deliveryRecipients(int $departmentId): array'), 'effective recipient list must include the responsible');
assert(repository.includes('$emails[] = $responsible;'), 'responsible must be added even when not in the configured list');
assert(migration.includes("ALTER TABLE departments ADD COLUMN responsible_email TEXT NOT NULL DEFAULT ''"), 'migration must add backward-compatible responsible column');
assert(mailer.includes('public static function buildDepartmentReplyTo('), 'reply-to helper must be testable');
assert(mailer.includes('$responsibleKey'), 'reply-to helper must exclude responsible');
assert(mailer.includes('$recipients[] = $responsibleEmail;'), 'mailer must always send the file to the responsible');
assert(controller.includes('$departments->deliveryRecipients($departmentId)'), 'history resend must resolve the responsible as a delivery recipient');
assert(controller.includes('$departments->responsibleEmail($departmentId)'), 'history resend must pass responsible address');
assert(controller.includes('$departments->responsibleEmail((int) $file[\'department_id\'])'), 'new sends must pass responsible address');
assert(version.includes("VERSION = '1.2.31'") && version.includes('SCHEMA_TARGET = 6'), 'application and schema versions must be updated');
console.log('OK: responsable del departamento, persistencia, migración 002 y exclusión en Reply-To para envíos y reenvíos.');
